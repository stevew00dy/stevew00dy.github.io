import type { ArmorItem, ArmorVariant, SetPiece } from '../types'

function pieces(definitions: Array<[string, string]>): SetPiece[] {
  return definitions.map(([slot, item]) => ({ slot, item }))
}

function variant(id: string, name: string, pieceDefinitions: Array<[string, string]>, note?: string): ArmorVariant {
  return {
    id,
    name,
    pieces: pieces(pieceDefinitions),
    note,
  }
}

